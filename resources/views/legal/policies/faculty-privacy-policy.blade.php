<p>Business Navachar School (BNS) is committed to protecting the privacy, dignity, professional reputation, and personal information of all faculty members associated with the institution.</p>
<p>These policies apply to all Full-Time Faculty, Visiting Expert Faculty, Guest Faculty, Industry Mentors, Corporate Trainers, Academic Advisors, and Faculties of IIM Trained Business Education Mentors associated with Business Navachar School.</p>

<hr>

<h2>23. Faculty Information Policy</h2>
<p>Business Navachar School collects faculty information only for legitimate academic, administrative, operational, legal, and institutional purposes.</p>
<p>Faculty information may include:</p>
<ul>
    <li>Full Name</li>
    <li>Professional Photograph</li>
    <li>Educational Qualifications</li>
    <li>Professional Certifications</li>
    <li>Areas of Expertise</li>
    <li>Industry Experience</li>
    <li>Employment History</li>
    <li>Resume / Curriculum Vitae</li>
    <li>Contact Information</li>
    <li>LinkedIn Profile</li>
    <li>Research Publications</li>
    <li>Books &amp; Articles</li>
    <li>Professional Memberships</li>
    <li>Awards &amp; Recognition</li>
    <li>Languages Known</li>
    <li>Faculty Identification Number</li>
    <li>Faculty Joining Date</li>
    <li>Training Records</li>
</ul>
<p>Faculty information is maintained securely and is accessible only to authorized personnel on a need-to-know basis.</p>
<p>Information published on the BNS website is limited to professional details intended to help learners understand the faculty's qualifications and areas of expertise.</p>
<p>Personal information that is not relevant to professional representation will not be publicly disclosed without consent.</p>

