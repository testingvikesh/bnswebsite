<h2>85. Cyber Incident Response Policy</h2>
<p>Business Navachar School has established an organized Cyber Incident Response Framework to detect, analyze, contain, recover from, and learn from cybersecurity incidents.</p>
<p>Cyber incidents may include:</p>
<ul>
    <li>Unauthorized access</li>
    <li>Website hacking</li>
    <li>Malware</li>
    <li>Virus attacks</li>
    <li>Ransomware</li>
    <li>Phishing</li>
    <li>Fake websites</li>
    <li>Fake mobile applications</li>
    <li>Database compromise</li>
    <li>Data leakage</li>
    <li>Email hacking</li>
    <li>Payment fraud</li>
    <li>Cloud infrastructure compromise</li>
    <li>Insider threats</li>
    <li>Network attacks</li>
    <li>Credential theft</li>
</ul>
<p>When an incident is identified, BNS may initiate the following response process:</p>
<h3>Phase 1 – Identification</h3>
<ul>
    <li>Detect unusual activity</li>
    <li>Verify incident authenticity</li>
    <li>Assess severity</li>
</ul>
<h3>Phase 2 – Containment</h3>
<ul>
    <li>Isolate affected systems</li>
    <li>Restrict unauthorized access</li>
    <li>Preserve digital evidence</li>
</ul>
<h3>Phase 3 – Investigation</h3>
<ul>
    <li>Determine root cause</li>
    <li>Assess affected information</li>
    <li>Review security logs</li>
</ul>
<h3>Phase 4 – Recovery</h3>
<ul>
    <li>Restore systems</li>
    <li>Recover backups</li>
    <li>Verify system integrity</li>
    <li>Resume operations</li>
</ul>
<h3>Phase 5 – Improvement</h3>
<ul>
    <li>Update security controls</li>
    <li>Conduct internal review</li>
    <li>Improve future preparedness</li>
</ul>
<p>Where required by applicable law, affected stakeholders may be informed of significant security incidents.</p>

