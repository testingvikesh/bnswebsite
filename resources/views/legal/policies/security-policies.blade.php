<h2>86. Vulnerability Disclosure Policy</h2>
<p>Business Navachar School encourages ethical cybersecurity researchers and responsible security professionals to report genuine vulnerabilities.</p>
<p>Researchers should:</p>
<ul class="bns-legal__checks">
    <li>Act responsibly.</li>
    <li>Avoid harming systems.</li>
    <li>Avoid accessing personal information.</li>
    <li>Avoid disrupting services.</li>
    <li>Provide sufficient technical details.</li>
</ul>
<p>Reports should include:</p>
<ul>
    <li>Description</li>
    <li>URL</li>
    <li>Affected feature</li>
    <li>Reproduction steps</li>
    <li>Screenshots</li>
    <li>Suggested mitigation</li>
</ul>
<p>Business Navachar School appreciates responsible disclosure and will review reported vulnerabilities in good faith.</p>

