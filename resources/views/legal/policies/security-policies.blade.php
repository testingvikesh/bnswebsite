<h2>87. Fraud Prevention Policy</h2>
<p>Business Navachar School maintains a Zero Tolerance Policy against fraud.</p>
<p>Fraud may include:</p>
<ul>
    <li>Fake admission offers</li>
    <li>Fake appointment letters</li>
    <li>Fake faculty identity</li>
    <li>Fake certificates</li>
    <li>Fake websites</li>
    <li>Fake payment links</li>
    <li>Fake WhatsApp numbers</li>
    <li>Fake QR Codes</li>
    <li>Unauthorized fundraising</li>
    <li>Misuse of BNS logo</li>
    <li>Social media impersonation</li>
</ul>
<p>Users should:</p>
<ul class="bns-legal__checks">
    <li>Verify official communication.</li>
    <li>Pay only through official channels.</li>
    <li>Verify bank details.</li>
    <li>Request official receipts.</li>
    <li>Report suspicious messages immediately.</li>
</ul>
<p>Any fraud involving the BNS name may be reported to appropriate legal authorities where necessary.</p>

