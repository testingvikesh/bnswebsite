<p>Business Navachar School (BNS) is more than an educational institution—it is a lifelong learning and business community that connects students, entrepreneurs, professionals, faculty members, alumni, mentors, investors, industry experts, and innovators.</p>
<p>To ensure a positive, respectful, safe, and productive environment, every member of the BNS Community is expected to follow these Community Policies.</p>

<hr>

<h2>76. Student Community Guidelines</h2>
<p>Business Navachar School encourages every learner to become a responsible member of the BNS Learning Community.</p>
<p>The Student Community includes:</p>
<ul>
    <li>School Students</li>
    <li>College Students</li>
    <li>Women Entrepreneurs</li>
    <li>Job Professionals</li>
    <li>Business Owners</li>
    <li>Startup Founders</li>
    <li>Business Professionals</li>
</ul>
<p>All community members are expected to:</p>
<ul class="bns-legal__checks">
    <li>Respect every participant regardless of age, gender, profession, religion, language, or background.</li>
    <li>Communicate professionally and respectfully.</li>
    <li>Encourage collaborative learning.</li>
    <li>Support fellow learners.</li>
    <li>Participate actively in discussions.</li>
    <li>Share knowledge responsibly.</li>
    <li>Follow faculty instructions.</li>
    <li>Respect institutional policies.</li>
    <li>Maintain academic honesty.</li>
    <li>Protect confidential information shared during learning activities.</li>
</ul>
<p>Students shall not:</p>
<ul>
    <li>Use abusive language.</li>
    <li>Harass or threaten others.</li>
    <li>Spread misinformation.</li>
    <li>Promote hate speech or discrimination.</li>
    <li>Share offensive content.</li>
    <li>Spam groups or forums.</li>
    <li>Promote unauthorized commercial activities.</li>
    <li>Misuse the BNS name or logo.</li>
    <li>Share copyrighted learning materials without permission.</li>
</ul>
<p>Business Navachar School reserves the right to suspend or terminate community access for violations of these guidelines.</p>

