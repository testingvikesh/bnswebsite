<h2>5. Expulsion or Disciplinary Action</h2>
<p>If a student's admission is cancelled due to:</p>
<ul>
    <li>Misconduct</li>
    <li>Violation of Institutional Policies</li>
    <li>Academic Dishonesty</li>
    <li>Fraudulent Documents</li>
    <li>Misuse of BNS Name or Brand</li>
    <li>Criminal Activities</li>
    <li>Harassment</li>
    <li>Damage to Institutional Property</li>
</ul>
<p>or any other serious policy violation,</p>
<p>no refund shall be granted.</p>

