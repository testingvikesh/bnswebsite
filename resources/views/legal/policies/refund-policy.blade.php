<h2>3. Cancellation by Student</h2>
<p>If a student voluntarily:</p>
<ul>
    <li>Cancels admission</li>
    <li>Withdraws from the program</li>
    <li>Stops attending classes</li>
    <li>Changes personal plans</li>
    <li>Moves to another city or country</li>
    <li>Accepts employment elsewhere</li>
    <li>Joins another educational institution</li>
    <li>Faces personal or family circumstances</li>
    <li>Is unable to continue for any reason</li>
</ul>
<p>the fees already paid will not be refunded.</p>

