<h2>4. Non-Attendance</h2>
<p>Failure to attend:</p>
<ul>
    <li>Classes</li>
    <li>Workshops</li>
    <li>Seminars</li>
    <li>Business Events</li>
    <li>Faculty Sessions</li>
    <li>Online Sessions</li>
</ul>
<p>does not entitle the participant to any refund, credit, or compensation.</p>

