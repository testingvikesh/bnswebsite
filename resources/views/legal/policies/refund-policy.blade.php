<h2>2. No Refund Policy</h2>
<p>All fees paid to Business Navachar School are final and non-refundable.</p>
<p>Once any payment is made towards:</p>
<ul>
    <li>Admission Fee</li>
    <li>Registration Fee</li>
    <li>Annual Program Fee</li>
    <li>Tuition Fee</li>
    <li>Workshop Fee</li>
    <li>Seminar Fee</li>
    <li>Event Registration Fee</li>
    <li>Certification Fee</li>
    <li>Digital Learning Access Fee</li>
    <li>Business Kit Fee</li>
    <li>Learning Material Fee</li>
    <li>Faculty Development Program Fee</li>
