<p>Business Navachar School (BNS) is committed to maintaining the highest standards of integrity, transparency, accountability, fairness, professionalism, and ethical conduct in all its educational, administrative, financial, academic, and business activities.</p>
<p>These Governance Policies apply to all students, parents, faculty members, visiting experts, mentors, business coaches, employees, volunteers, franchise partners, centre partners, vendors, consultants, corporate partners, sponsors, donors, and every person associated with Business Navachar School.</p>

<hr>

<h2>80. Ethics Policy</h2>
<p>Business Navachar School believes that education should be built on strong ethical values.</p>
<p>Every member of the BNS community is expected to uphold the following principles:</p>
<ul class="bns-legal__checks">
    <li>Integrity</li>
    <li>Honesty</li>
    <li>Accountability</li>
    <li>Respect</li>
    <li>Professionalism</li>
    <li>Fairness</li>
    <li>Transparency</li>
    <li>Responsibility</li>
    <li>Confidentiality</li>
    <li>Excellence</li>
</ul>
<p>Members shall:</p>
<ul>
    <li>Act honestly in all academic and professional activities.</li>
    <li>Respect institutional policies.</li>
    <li>Protect confidential information.</li>
    <li>Avoid conflicts of interest.</li>
    <li>Maintain professional behaviour.</li>
    <li>Respect intellectual property.</li>
    <li>Promote ethical entrepreneurship.</li>
    <li>Represent Business Navachar School responsibly.</li>
</ul>
<p>Business Navachar School does not tolerate unethical conduct, fraud, academic dishonesty, corruption, or misuse of institutional resources.</p>

<hr>

<h2>81. Anti-Bribery &amp; Anti-Corruption Policy</h2>
<p>Business Navachar School follows a zero-tolerance approach towards bribery and corruption.</p>
<p>No employee, faculty member, student, consultant, partner, vendor, or representative shall:</p>
<ul>
    <li>Offer bribes.</li>
    <li>Accept bribes.</li>
    <li>Demand illegal payments.</li>
    <li>Offer gifts in exchange for institutional favours.</li>
    <li>Manipulate admissions.</li>
    <li>Influence evaluations improperly.</li>
    <li>Misuse institutional authority.</li>
    <li>Engage in financial misconduct.</li>
</ul>
<p>Admissions, faculty appointments, certifications, partnerships, procurement, scholarships, and institutional decisions shall be based on transparent and objective criteria.</p>
<p>Any suspected bribery or corruption should be reported immediately to the BNS Governance Committee or Grievance Officer.</p>
<p>Reports made in good faith will be handled confidentially.</p>

<hr>

<h2>82. Anti-Harassment Policy</h2>
<p>Business Navachar School is committed to providing a safe, respectful, inclusive, and harassment-free learning and working environment.</p>
<p>Harassment of any kind is strictly prohibited.</p>
<p>Harassment may include:</p>
<ul>
    <li>Verbal Abuse</li>
    <li>Physical Harassment</li>
    <li>Psychological Harassment</li>
    <li>Sexual Harassment</li>
    <li>Online Harassment</li>
    <li>Cyberbullying</li>
    <li>Threatening Behaviour</li>
    <li>Intimidation</li>
    <li>Stalking</li>
    <li>Humiliation</li>
    <li>Offensive Messages</li>
    <li>Inappropriate Images</li>
</ul>
<p>Harassment is prohibited during:</p>
<ul>
    <li>Classroom Sessions</li>
    <li>Workshops</li>
    <li>Seminars</li>
    <li>Online Classes</li>
    <li>WhatsApp Groups</li>
    <li>Student Communities</li>
    <li>Social Media</li>
    <li>Events</li>
    <li>Business Networking Activities</li>
</ul>
<p>Business Navachar School will investigate complaints fairly and confidentially.</p>
<p>Appropriate disciplinary action may be taken where policy violations are established.</p>

<hr>

<h2>83. Anti-Discrimination Policy</h2>
<p>Business Navachar School believes that education should be accessible in an environment of dignity and mutual respect.</p>
<p>Business Navachar School does not discriminate in admissions, learning opportunities, employment, partnerships, or institutional services on unlawful grounds.</p>
<p>All participants are expected to treat one another with fairness and respect.</p>
<p>Discrimination, exclusion, or unfair treatment that violates applicable law or institutional policy is not permitted.</p>
<p>Every learner deserves equal respect, encouragement, and opportunity to participate in the BNS learning ecosystem.</p>

