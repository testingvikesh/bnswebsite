<p>Business Navachar School (BNS) recognizes that parents and guardians play a vital role in a student's educational journey. We are committed to maintaining transparent communication while protecting the privacy, dignity, and personal information of both students and their parents.</p>
<p>These policies apply primarily to parents and legal guardians of students enrolled in the School Students Entrepreneurship Program and, where applicable, to participants below 18 years of age.</p>

<hr>

<h2>19. Parent Communication Policy</h2>
<p>Business Navachar School believes that effective parent communication contributes significantly to a student's growth and success.</p>
<p>Parents or legal guardians may receive official communications regarding:</p>
<ul>
    <li>Admission Updates</li>
    <li>Fee Payment Reminders</li>
    <li>Orientation Programs</li>
    <li>Academic Calendar</li>
    <li>Weekly Class Schedule</li>
    <li>Attendance Updates</li>
    <li>Student Performance Reports</li>
    <li>Workshops</li>
    <li>Events</li>
    <li>Competitions</li>
    <li>Holiday Notices</li>
    <li>Emergency Announcements</li>
    <li>Certificates</li>
    <li>Graduation Ceremonies</li>
    <li>Parent Meetings</li>
</ul>
<p>Communication may be sent through:</p>
<ul>
    <li>Phone Calls</li>
    <li>WhatsApp</li>
    <li>SMS</li>
    <li>Email</li>
    <li>Student Portal</li>
    <li>Parent Portal</li>
    <li>Official Website</li>
    <li>Printed Circulars</li>
</ul>
<p>Parents are requested to keep their contact details updated to ensure timely communication.</p>
<p>Business Navachar School shall not be responsible for communication delays caused by incorrect or outdated contact information provided by the parent.</p>

<hr>

<h2>20. Parent Portal Privacy Policy</h2>
<p>Business Navachar School may provide a secure Parent Portal to help parents stay informed about their child's learning journey.</p>
<p>The Parent Portal may include:</p>
<ul>
    <li>Student Attendance</li>
    <li>Academic Progress</li>
    <li>Assignment Status</li>
    <li>Project Updates</li>
    <li>Event Information</li>
    <li>Fee Status</li>
    <li>Certificates</li>
    <li>Notices</li>
    <li>Timetable</li>
    <li>Learning Resources</li>
    <li>Parent Meeting Schedule</li>
</ul>
<p>Each parent will receive secure login credentials.</p>
<p>Parents are responsible for:</p>
<ul>
    <li>Keeping login credentials confidential.</li>
    <li>Not sharing portal access with unauthorized individuals.</li>
    <li>Logging out after using shared devices.</li>
</ul>
<p>Unauthorized access or misuse of the Parent Portal may result in suspension of access and further action where necessary.</p>

<hr>

<h2>21. Student Safety Information Policy</h2>
<p>The safety and well-being of every student is a top priority at Business Navachar School.</p>
<p>For safety and emergency purposes, BNS may maintain information including:</p>
<ul>
    <li>Parent Contact Details</li>
    <li>Emergency Contact Numbers</li>
    <li>Authorized Guardian Information</li>
    <li>Medical Information voluntarily provided by parents</li>
    <li>Emergency Medical Consent (where applicable)</li>
</ul>
<p>This information is used only for:</p>
<ul>
    <li>Student Safety</li>
    <li>Emergency Communication</li>
    <li>Health Emergencies</li>
    <li>Disaster Management</li>
    <li>Institutional Safety</li>
</ul>
<p>Business Navachar School maintains appropriate safeguards to protect such information and limits access to authorized personnel only.</p>
<p>Information will not be disclosed to third parties unless required by law or necessary to protect the health or safety of the student.</p>

<hr>

<h2>22. Parent Consent Management Policy</h2>
<p>For participants below the age of 18 years, Business Navachar School may require the consent of a parent or legal guardian for specific activities.</p>
<p>Parent or guardian consent may be requested for:</p>
<ul>
    <li>Admission Registration</li>
    <li>Program Enrollment</li>
    <li>Online Learning Participation</li>
    <li>Photography &amp; Videography</li>
    <li>Educational Tours</li>
    <li>Workshops &amp; Competitions</li>
    <li>Guest Sessions</li>
    <li>Digital Learning Platforms</li>
    <li>Student Projects</li>
    <li>Research Activities</li>
    <li>Participation in Promotional Materials</li>
    <li>Emergency Medical Assistance (where applicable)</li>
</ul>
<p>Parents may update or withdraw consent for optional activities by submitting a written request to the BNS Administration.</p>
<p>Withdrawal of consent will not affect activities or processes that are legally required or already completed before the request was received.</p>
<p>Business Navachar School maintains records of parent consents to ensure compliance with institutional policies and applicable legal requirements.</p>

<hr>

<h2>Parent Rights</h2>
<p>Parents have the right to:</p>
<ul class="bns-legal__checks">
    <li>Receive timely academic and administrative updates.</li>
    <li>Access information about their child's progress through authorized channels.</li>
    <li>Request correction of inaccurate parent or student information.</li>
    <li>Participate in parent meetings and orientation sessions.</li>
    <li>Raise concerns or grievances through the official grievance redressal process.</li>
    <li>Protect the privacy of their child's personal information in accordance with applicable laws and institutional policies.</li>
</ul>

<hr>

<h2>Parent Responsibilities</h2>
<p>Parents are expected to:</p>
<ul>
    <li>Provide accurate and updated contact information.</li>
    <li>Inform BNS of any emergency contact changes.</li>
    <li>Respect the privacy of other students and families.</li>
    <li>Use the Parent Portal responsibly.</li>
    <li>Support their child's regular attendance and participation.</li>
    <li>Follow official communication channels for academic and administrative matters.</li>
</ul>

<hr>

<h2>BNS Commitment to Parents</h2>
<p>Business Navachar School is committed to building a transparent, respectful, and collaborative relationship with every parent.</p>
<p>Through responsible communication, secure digital systems, and strong privacy practices, we strive to create a safe, supportive, and trusted educational environment where students can learn, grow, and become future entrepreneurs, leaders, and responsible citizens.</p>

