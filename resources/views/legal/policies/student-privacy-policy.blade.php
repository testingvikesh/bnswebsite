<hr>

<h2>18. Student ID Policy</h2>
<p>Every admitted participant receives a unique Business Navachar School Student ID.</p>
<p>The Student ID may be used for:</p>
<ul>
    <li>Identity Verification</li>
    <li>Attendance</li>
    <li>Portal Login</li>
    <li>Event Registration</li>
    <li>Workshop Participation</li>
    <li>Certificate Verification</li>
    <li>Library Access (where applicable)</li>
    <li>Learning Resources</li>
</ul>
<p>Students are responsible for maintaining the confidentiality of their Student ID credentials.</p>
<p>Misuse, duplication, impersonation, or unauthorized use of a Student ID may lead to disciplinary action.</p>
<p>Upon completion or discontinuation of the program, Student IDs may be deactivated while academic records are retained according to institutional policies.</p>

<hr>

<h2>Student Privacy Commitment</h2>
<p>Business Navachar School is committed to protecting every student's academic records, personal information, intellectual contributions, and learning journey with fairness, integrity, and confidentiality.</p>
<p>We continuously strengthen our academic systems, digital infrastructure, and privacy practices to ensure a secure and trusted learning environment for every participant.</p>

