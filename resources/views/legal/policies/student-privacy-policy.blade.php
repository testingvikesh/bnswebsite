<p>Business Navachar School (BNS) is committed to protecting the privacy, dignity, and academic records of every student. These Student Privacy Policies apply to all learners enrolled in BNS programs, including School Students, College Students, Women Entrepreneurs, Job Professionals, and Business Owners.</p>

<hr>

<h2>11. Student Records Policy</h2>
<p>Business Navachar School maintains student records to ensure effective academic administration and student support.</p>
<p>Student records may include:</p>
<ul>
    <li>Admission Details</li>
    <li>Personal Information</li>
    <li>Parent/Guardian Information (where applicable)</li>
    <li>Educational Qualifications</li>
    <li>Attendance Records</li>
    <li>Program Enrollment</li>
    <li>Fee Records</li>
    <li>Academic Progress</li>
    <li>Certificates</li>
    <li>Student ID Information</li>
</ul>
<p>These records are maintained securely and are accessible only to authorized personnel for academic and administrative purposes.</p>
<p>Students are encouraged to keep their records updated throughout their learning journey.</p>

<hr>

<h2>12. Academic Records Policy</h2>
<p>Business Navachar School maintains accurate academic records for every participant.</p>
<p>Academic records may include:</p>
<ul>
    <li>Attendance</li>
    <li>Learning Hours</li>
    <li>Assignments</li>
    <li>Business Projects</li>
    <li>Research Activities</li>
    <li>Presentations</li>
    <li>Assessments</li>
    <li>Workshop Participation</li>
    <li>Seminar Participation</li>
    <li>Certificates Earned</li>
</ul>
<p>Academic records are used for:</p>
<ul class="bns-legal__checks">
    <li>Academic Evaluation</li>
    <li>Progress Monitoring</li>
    <li>Certificate Eligibility</li>
    <li>Student Development</li>
    <li>Institutional Quality Improvement</li>
</ul>
<p>Academic records remain confidential and are not disclosed without appropriate authorization except where required by law.</p>

<hr>

<h2>13. Assignment Privacy Policy</h2>
<p>Assignments submitted by students are treated as confidential academic work.</p>
<p>Assignments may be used for:</p>
<ul>
    <li>Faculty Evaluation</li>
    <li>Academic Feedback</li>
    <li>Learning Improvement</li>
    <li>Internal Academic Review</li>
</ul>
<p>Students are expected to submit original work.</p>
<p>Plagiarism, copying, or unauthorized use of another participant's work may result in academic action according to BNS policies.</p>
<p>Assignments will not be published publicly without the student's permission, except where anonymized for educational purposes.</p>

<hr>

<h2>14. Project Ownership Policy</h2>
<p>Business Navachar School encourages innovation and practical business development.</p>
<p>Unless otherwise agreed in writing:</p>
<ul>
    <li>Business ideas remain the intellectual property of the student.</li>
    <li>Project reports remain the property of the student.</li>
    <li>Startup concepts belong to the creator.</li>
</ul>
<p>However, BNS may retain copies of submitted projects for:</p>
<ul>
    <li>Academic Evaluation</li>
    <li>Quality Assurance</li>
    <li>Internal Training</li>
    <li>Institutional Research</li>
</ul>
<p>If a student wishes to showcase a project publicly through the BNS website, events, or promotional materials, separate consent may be requested.</p>

<hr>

<h2>15. Research Submission Policy</h2>
<p>Participants may submit research papers, market studies, business plans, innovation reports, and other academic work.</p>
<p>Research submissions may be used for:</p>
<ul>
    <li>Academic Evaluation</li>
    <li>Faculty Feedback</li>
    <li>Internal Learning</li>
    <li>Student Development</li>
</ul>
<p>BNS respects the originality of every research submission.</p>
<p>Any publication, presentation, or public use of a participant's research by BNS will be subject to appropriate permissions where applicable.</p>

<hr>

<h2>16. Assessment Data Policy</h2>
<p>Business Navachar School follows a continuous learning and assessment model.</p>
<p>Assessment data may include:</p>
<ul>
    <li>Attendance</li>
    <li>Assignments</li>
    <li>Projects</li>
    <li>Presentations</li>
    <li>Business Case Studies</li>
    <li>Practical Activities</li>
    <li>Participation</li>
</ul>
