<hr>

<h2>17. Student Performance Reports Policy</h2>
<p>Business Navachar School may prepare periodic performance reports to help learners understand their progress.</p>
<p>Performance reports may include:</p>
<ul>
    <li>Attendance Summary</li>
    <li>Learning Progress</li>
    <li>Assignment Completion</li>
    <li>Project Performance</li>
    <li>Participation</li>
    <li>Mentor Feedback</li>
    <li>Skill Development</li>
    <li>Leadership Growth</li>
    <li>Business Competency Development</li>
