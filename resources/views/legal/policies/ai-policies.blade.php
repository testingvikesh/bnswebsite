<p>Business Navachar School (BNS) believes that Artificial Intelligence (AI) is transforming education, entrepreneurship, innovation, leadership, and business growth. BNS is committed to using AI responsibly, ethically, transparently, and in a manner that enhances learning while preserving academic integrity, human values, and learner privacy.</p>
<p>These policies apply to all students, parents, faculty members, mentors, visiting experts, business coaches, partners, and users of BNS digital learning platforms.</p>

<hr>

<h2>71. AI Ethics Policy</h2>
<p>Business Navachar School promotes the responsible, ethical, and transparent use of Artificial Intelligence.</p>
<p>AI technologies may be used to support:</p>
<ul>
    <li>Personalized Learning</li>
    <li>Business Simulations</li>
    <li>Entrepreneurship Education</li>
    <li>Digital Research</li>
    <li>Business Planning</li>
    <li>Innovation Projects</li>
    <li>Career Guidance</li>
    <li>Learning Recommendations</li>
    <li>Student Support</li>
    <li>Faculty Assistance</li>
    <li>Administrative Processes</li>
</ul>
<p>The use of AI at BNS is guided by the following principles:</p>
<ul class="bns-legal__checks">
    <li>Human-Centred Learning</li>
    <li>Academic Integrity</li>
    <li>Transparency</li>
    <li>Fairness</li>
    <li>Privacy Protection</li>
    <li>Responsible Innovation</li>
    <li>Accountability</li>
    <li>Continuous Human Oversight</li>
</ul>
<p>AI is intended to assist learners and educators—not replace human teaching, mentoring, creativity, judgment, or decision-making.</p>
<p>Participants are expected to use AI responsibly and ethically in all academic and professional activities.</p>

<hr>

<h2>72. AI Generated Content Policy</h2>
<p>Business Navachar School recognizes that AI tools can assist in creating educational content, research, business ideas, reports, presentations, and learning materials.</p>
<p>Students and faculty may use AI tools to:</p>
<ul>
    <li>Brainstorm Ideas</li>
    <li>Improve Writing</li>
    <li>Translate Content</li>
    <li>Summarize Information</li>
    <li>Generate Business Models</li>
    <li>Prepare Presentations</li>
    <li>Analyze Data</li>
    <li>Learn New Concepts</li>
</ul>
<p>However, participants must ensure that:</p>
<ul>
    <li>AI-generated work is reviewed for accuracy.</li>
    <li>Critical thinking remains central to learning.</li>
    <li>Original ideas are properly distinguished from AI-assisted content.</li>
    <li>Applicable citation or disclosure requirements established by BNS or the instructor are followed.</li>
    <li>AI is not used to engage in plagiarism, academic dishonesty, or misrepresentation.</li>
</ul>
<p>Business Navachar School reserves the right to review AI-assisted submissions as part of academic quality assurance.</p>

<hr>

<h2>73. AI Mentor Disclaimer</h2>
<p>Business Navachar School may provide AI-powered digital assistants, learning tools, or virtual mentoring support to improve learner engagement.</p>
<p>Participants should understand that:</p>
<ul>
    <li>AI mentors provide general educational guidance.</li>
    <li>AI responses may not always be complete, current, or suitable for every situation.</li>
    <li>AI tools do not replace faculty members, business coaches, industry experts, mentors, or academic advisors.</li>
    <li>Important academic, business, legal, financial, or career decisions should be discussed with qualified human mentors or relevant professionals.</li>
</ul>
<p>Business Navachar School encourages learners to combine AI-assisted learning with faculty guidance, practical experience, and independent thinking.</p>

<hr>

<h2>74. Chatbot Privacy Policy</h2>
<p>Business Navachar School may provide AI-powered chatbots or virtual assistants through its website, mobile applications, student portal, admission portal, or other digital platforms.</p>
<p>Chatbots may assist users with:</p>
<ul>
    <li>Admission Enquiries</li>
    <li>Program Information</li>
    <li>Course Details</li>
    <li>Eligibility Guidance</li>
    <li>Fee Information</li>
    <li>Event Registration</li>
    <li>Student Support</li>
    <li>Technical Assistance</li>
    <li>Frequently Asked Questions</li>
</ul>
<p>To improve services, chatbot interactions may be securely recorded and analyzed.</p>
<p>Information shared with chatbots should be limited to what is necessary for obtaining support.</p>
<p>Users should not share highly sensitive information such as:</p>
<ul>
    <li>Banking Passwords</li>
    <li>UPI PINs</li>
    <li>Credit/Debit Card Details</li>
    <li>Government Passwords</li>
    <li>Personal Authentication Credentials</li>
</ul>
<p>Chatbot conversations are handled in accordance with the BNS Privacy Policy and applicable institutional practices.</p>

